    def record_fixture_settlement_attempt(
        self,
        fixture_id: int,
        *,
        fixture_status: str | None,
        reason: str,
        state: str = "RETRY",
        increment_retry: bool = True,
        increment_recovery: bool = False,
        next_retry_at: str | None = None,
    ) -> int:
        """Persist settlement diagnostics and return the current retry count."""
        values: dict[str, Any] = {
            "settlement_checked_at": datetime.now(timezone.utc).isoformat(),
            "settlement_state": state,
            "settlement_reason": reason,
            "last_api_status": str(fixture_status or "UNKNOWN"),
            "next_retry_at": next_retry_at,
        }
        if fixture_status is not None:
            values["fixture_status"] = str(fixture_status)
        if increment_retry:
            values["settlement_retry_count"] = func.coalesce(self._predictions.c.settlement_retry_count, 0) + 1
        if increment_recovery:
            values["recovery_attempts"] = func.coalesce(self._predictions.c.recovery_attempts, 0) + 1
        statement = (
            update(self._predictions)
            .where(
                self._predictions.c.fixture_id == int(fixture_id),
                self._predictions.c.result == "PENDING",
            )
            .values(**values)
        )
        with self.engine.begin() as conn:
            conn.execute(statement)
            retry = conn.execute(
                select(self._predictions.c.settlement_retry_count)
                .where(self._predictions.c.fixture_id == int(fixture_id), self._predictions.c.result == "PENDING")
                .order_by(self._predictions.c.settlement_retry_count.desc())
                .limit(1)
            ).scalar()
        return int(retry or 0)

