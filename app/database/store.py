    def sync_decision_record_for_fixture(self, fixture_id: int) -> None:
        if not fixture_id:
            return
        row = self.latest_prediction_by_fixture(fixture_id)
        if not row:
            return
        record = self._decision_snapshots.from_prediction_row(row)
        if record:
            self.upsert_decision_record(record)

    def rebuild_decision_records_from_predictions(self) -> int:
        rows = self._rows("""SELECT p.* FROM predictions p JOIN (
            SELECT fixture_id, MAX(id) AS max_id FROM predictions GROUP BY fixture_id
        ) latest ON latest.max_id=p.id ORDER BY p.id DESC""")
        count = 0
        for row in rows:
            record = DecisionSnapshotService().from_prediction_row(row)
            if record:
                self.upsert_decision_record(record)
                count += 1
        return count

