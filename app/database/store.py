    @staticmethod
    def _as_utc(value: Any) -> datetime | None:
        if value is None or value == "":
            return None
        if isinstance(value, datetime):
            dt = value
        else:
            dt = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt.astimezone(timezone.utc)

    def refresh_membership_status(self, user_id: int) -> dict[str, Any] | None:
        user = self.user_by_id(user_id)
        if not user:
            return None
        expiry = self._as_utc(user.get("membership_expires_at"))
        role = str(user.get("role") or "MEMBER").upper()
        status = str(user.get("status") or "ACTIVE").upper()
        if role not in {"ADMIN", "SUPER_ADMIN"} and expiry and datetime.now(timezone.utc) >= expiry and status == "ACTIVE":
            with self.engine.begin() as conn:
                conn.execute(text("UPDATE user_accounts SET status='EXPIRED',updated_at=:now WHERE id=:id"), {"now": datetime.now(timezone.utc), "id": user_id})
            user["status"] = "EXPIRED"
        return user

    def authenticate_user(self, username: str, password: str) -> tuple[dict[str, Any] | None, str | None]:
        from app.security import verify_password
        user = self.user_by_username(username)
        if not user or not verify_password(password, str(user.get("password_hash") or "")):
            return None, "Username atau password salah."
        user = self.refresh_membership_status(int(user["id"])) or user
        status = str(user.get("status") or "DISABLED").upper()
        if status == "EXPIRED":
            return None, "Masa aktif akun Anda telah berakhir. Hubungi administrator untuk perpanjangan."
        if status != "ACTIVE":
            return None, "Akun Anda sedang dinonaktifkan. Hubungi administrator."
