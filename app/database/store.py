    def recover_fixture_id(self, old_fixture_id: int, new_fixture_id: int, *, reason: str) -> int:
        """Move pending predictions to a recovered API fixture ID safely."""
        if int(old_fixture_id) == int(new_fixture_id):
            return 0
        updated = 0
        with self.engine.begin() as conn:
            old_rows = conn.execute(
                select(self._predictions.c.id, self._predictions.c.pick)
                .where(self._predictions.c.fixture_id == int(old_fixture_id), self._predictions.c.result == "PENDING")
                .with_for_update()
            ).mappings().all()
            for row in old_rows:
                duplicate = conn.execute(
                    select(self._predictions.c.id).where(
                        self._predictions.c.fixture_id == int(new_fixture_id),
                        self._predictions.c.pick == row["pick"],
                        self._predictions.c.result == "PENDING",
                    ).limit(1)
                ).scalar()
                if duplicate and int(duplicate) != int(row["id"]):
                    conn.execute(self._predictions.delete().where(self._predictions.c.id == int(duplicate)))
                result = conn.execute(
                    update(self._predictions)
                    .where(self._predictions.c.id == int(row["id"]), self._predictions.c.result == "PENDING")
                    .values(
                        fixture_id=int(new_fixture_id),
                        recovered_from_fixture_id=int(old_fixture_id),
                        settlement_state="RECOVERED",
                        settlement_reason=reason,
                        settlement_checked_at=datetime.now(timezone.utc).isoformat(),
                        recovery_attempts=func.coalesce(self._predictions.c.recovery_attempts, 0) + 1,
                    )
                )
                updated += int(result.rowcount or 0)
        return updated


