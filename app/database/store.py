class Store:
    def __init__(self, database_url: str) -> None:
        self.database_url = database_url
        self.engine: Engine = create_engine(database_url, pool_pre_ping=True, future=True)
        self._init()
        bootstrap_database(self.engine)
        self._metadata = MetaData()
        self._predictions = Table("predictions", self._metadata, autoload_with=self.engine)
        self._decision_snapshots = DecisionSnapshotService()
        self.rebuild_decision_records_from_predictions()
        self.refresh_performance_intelligence()

    def _init(self) -> None:
        # SQLite does not support GENERATED BY DEFAULT AS IDENTITY.
        if self.database_url.startswith("sqlite"):
            schema = [s.replace("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT") for s in SCHEMA]
        else:
            schema = SCHEMA
        # Create base schema in a clean transaction. Never catch a database error
        # inside an active PostgreSQL transaction: doing so leaves the transaction
        # aborted and causes every later statement to fail with
        # InFailedSqlTransaction.
        with self.engine.begin() as conn:
            for statement in schema:
                conn.execute(text(statement))

        # Additive migration, guarded by schema inspection rather than relying on
        # an exception from ALTER TABLE. This is safe on PostgreSQL and SQLite.
        columns = {column["name"] for column in inspect(self.engine).get_columns("predictions")}
        additive_columns = {
            "settlement_checked_at": "TEXT",
            "settlement_state": "TEXT DEFAULT 'PENDING'",
            "settlement_reason": "TEXT",
            "settlement_retry_count": "INTEGER DEFAULT 0",
            "next_retry_at": "TEXT",
            "recovery_attempts": "INTEGER DEFAULT 0",
            "recovered_from_fixture_id": "BIGINT",
            "last_api_status": "TEXT",
            "settlement_eligible": "INTEGER DEFAULT 1",
        }
        for column_name, column_type in additive_columns.items():
            if column_name not in columns:
                with self.engine.begin() as conn:
                    conn.execute(text(f"ALTER TABLE predictions ADD COLUMN {column_name} {column_type}"))

        # Reconcile legacy observations. NO BET/MONITOR rows are analytical
        # snapshots, not wagers, and must never inflate the settlement queue.
        with self.engine.begin() as conn:
            conn.execute(text("""
                UPDATE predictions
                SET settlement_eligible = CASE
                    WHEN UPPER(COALESCE(pick_role,'')) IN ('NO_BET','NO PICK','NO_PICK','MONITOR','WATCH')
                      OR UPPER(REPLACE(COALESCE(pick,''),'_',' ')) IN ('NO BET','NO PICK')
                      OR UPPER(COALESCE(market_key,'')) = 'NO_BET'
                    THEN 0 ELSE COALESCE(settlement_eligible,1) END
            """))
            conn.execute(text("""
                UPDATE predictions
                SET settlement_state='NOT_APPLICABLE', next_retry_at=NULL
                WHERE result='PENDING' AND COALESCE(settlement_eligible,1)=0
            """))

        # Seed defaults in a separate transaction so a migration issue can never
        # poison application startup settings.
        with self.engine.begin() as conn:
            for key, value in DEFAULT_ADMIN_SETTINGS.items():
                conn.execute(
                    text("INSERT INTO app_settings(key,value) VALUES (:k,:v) ON CONFLICT(key) DO NOTHING"),
                    {"k": key, "v": json.dumps(value)},
                )

    def _rows(self, sql: str, params: dict[str, Any] | None = None) -> list[dict[str, Any]]:
        with self.engine.connect() as conn:
            return [dict(r._mapping) for r in conn.execute(text(sql), params or {})]

    def save_prediction(self, row: dict[str, Any]) -> None:
        payload = json.dumps(row, ensure_ascii=False, default=str)
        now = datetime.now(timezone.utc).isoformat()
        params = {
            "fixture_id": row.get("fixture_id"), "created_at": now, "league": row.get("league"),
            "home_team": row.get("home_team"), "away_team": row.get("away_team"), "pick": row.get("pick"),
            "pick_role": row.get("pick_role", "NO_BET"), "confidence": row.get("confidence"),
            "probability": row.get("probability"), "odds": row.get("odds"), "opening_odds": row.get("odds"),
            "ev": row.get("ev"), "pqi": row.get("pqi"), "payload": payload, "market_key": row.get("market_key"),
            "fixture_date": row.get("fixture_date"), "fixture_status": row.get("fixture_status"),
            "source": row.get("source", "MANUAL"), "league_id": row.get("league_id"), "season": row.get("season"),
            "calibration_bucket": self._bucket(row.get("probability")),
            "settlement_eligible": 1 if row.get("settlement_eligible", True) else 0,
            "settlement_state": "PENDING" if row.get("settlement_eligible", True) else "NOT_APPLICABLE",
            "settlement_reason": None if row.get("settlement_eligible", True) else "Observasi model; bukan rekomendasi settlement",
        }
        sql = """INSERT INTO predictions
        (fixture_id,created_at,league,home_team,away_team,pick,pick_role,confidence,probability,odds,opening_odds,ev,pqi,payload,market_key,fixture_date,fixture_status,source,league_id,season,calibration_bucket,settlement_eligible,settlement_state,settlement_reason)
        VALUES (:fixture_id,:created_at,:league,:home_team,:away_team,:pick,:pick_role,:confidence,:probability,:odds,:opening_odds,:ev,:pqi,:payload,:market_key,:fixture_date,:fixture_status,:source,:league_id,:season,:calibration_bucket,:settlement_eligible,:settlement_state,:settlement_reason)
        ON CONFLICT(fixture_id,pick) DO UPDATE SET
        created_at=excluded.created_at,pick_role=excluded.pick_role,confidence=excluded.confidence,probability=excluded.probability,
        odds=excluded.odds,ev=excluded.ev,pqi=excluded.pqi,payload=excluded.payload,market_key=excluded.market_key,
        fixture_date=excluded.fixture_date,fixture_status=excluded.fixture_status,source=excluded.source,
        settlement_eligible=excluded.settlement_eligible,
        settlement_state=CASE
          WHEN predictions.result='PENDING' AND excluded.settlement_eligible=0 THEN 'NOT_APPLICABLE'
          WHEN predictions.result='PENDING' AND excluded.settlement_eligible=1 AND predictions.settlement_state='NOT_APPLICABLE' THEN 'PENDING'
          ELSE predictions.settlement_state END"""
        with self.engine.begin() as conn:
            conn.execute(text(sql), params)
            # A fixture may be rescanned with a different market. Keep historical
            # snapshots, but only the newest decision remains settlement-eligible.
            conn.execute(text("""
                UPDATE predictions
                SET settlement_eligible=0,
                    settlement_state='SUPERSEDED',
                    settlement_reason='Digantikan snapshot keputusan terbaru',
                    next_retry_at=NULL
                WHERE fixture_id=:fixture_id
                  AND result='PENDING'
                  AND pick<>:pick
                  AND COALESCE(settlement_eligible,1)=1
            """), {"fixture_id": params["fixture_id"], "pick": params["pick"]})
            conn.execute(text("""INSERT INTO prediction_snapshots
                (fixture_id,created_at,pick,market_key,probability,confidence,pqi,payload)
                VALUES (:fixture_id,:created_at,:pick,:market_key,:probability,:confidence,:pqi,:payload)"""), params)
        self.sync_decision_record_for_fixture(int(row.get("fixture_id") or 0))

    @staticmethod
    def _bucket(probability: Any) -> str | None:
        if probability is None: return None
        p=float(probability)*100 if float(probability)<=1 else float(probability)
        lo=int(p//10)*10
        return f"{lo}-{min(100,lo+9)}"

    def recent_predictions(self, limit: int = 100) -> list[dict[str, Any]]:
        return self._rows("SELECT * FROM predictions ORDER BY id DESC LIMIT :n", {"n": limit})

    def prediction_history(
        self,
        *,
        date_from: str | None = None,
        date_to: str | None = None,
        result: str | None = None,
        fixture_status: str | None = None,
        search: str | None = None,
        limit: int = 500,
    ) -> list[dict[str, Any]]:
        clauses = []
        params: dict[str, Any] = {"n": max(1, min(int(limit), 2000))}
        if date_from:
            clauses.append("SUBSTR(fixture_date, 1, 10) >= :date_from")
            params["date_from"] = date_from
        if date_to:
            clauses.append("SUBSTR(fixture_date, 1, 10) <= :date_to")
            params["date_to"] = date_to
        if result and result.upper() != "ALL":
            clauses.append("result = :result")
            params["result"] = result.upper()
        if fixture_status and fixture_status.upper() != "ALL":
            clauses.append("fixture_status = :fixture_status")
            params["fixture_status"] = fixture_status.upper()
        if search:
            clauses.append("(LOWER(home_team) LIKE :search OR LOWER(away_team) LIKE :search OR LOWER(league) LIKE :search OR CAST(fixture_id AS TEXT) LIKE :search)")
            params["search"] = f"%{search.strip().lower()}%"
        where = f" WHERE {' AND '.join(clauses)}" if clauses else ""
        sql = f"SELECT * FROM predictions{where} ORDER BY fixture_date DESC, id DESC LIMIT :n"
        return self._rows(sql, params)

    def prediction_history_summary(self) -> dict[str, Any]:
        # Previous recovery query used:
        # SUBSTR(fixture_date, 1, 10) < CAST(CURRENT_DATE AS TEXT)
        # V8.0.2 supplies the WITA date as a bind parameter so PostgreSQL and
        # SQLite classify overdue fixtures using the same business day.
        # The business day follows WITA (UTC+8), not the database server clock.
        today_wita = datetime.now(ZoneInfo("Asia/Makassar")).date().isoformat()
        rows = self._rows("""SELECT
            COUNT(*) AS total,
            SUM(CASE WHEN result='PENDING' AND COALESCE(settlement_eligible,1)=1 THEN 1 ELSE 0 END) AS pending,
            SUM(CASE WHEN result='PENDING' AND COALESCE(settlement_eligible,1)=0 THEN 1 ELSE 0 END) AS observations,
            SUM(CASE WHEN result='WIN' THEN 1 ELSE 0 END) AS wins,
            SUM(CASE WHEN result='LOSS' THEN 1 ELSE 0 END) AS losses,
            SUM(CASE WHEN result='VOID' THEN 1 ELSE 0 END) AS voids,
            SUM(CASE WHEN result='PENDING' AND COALESCE(settlement_eligible,1)=1 AND SUBSTR(fixture_date, 1, 10) < :today AND COALESCE(settlement_state,'PENDING') <> 'NEEDS_INVESTIGATION' THEN 1 ELSE 0 END) AS overdue_pending,
            SUM(CASE WHEN result='PENDING' AND COALESCE(settlement_eligible,1)=1 AND settlement_state='NEEDS_INVESTIGATION' THEN 1 ELSE 0 END) AS needs_investigation
            FROM predictions""", {"today": today_wita})
        return rows[0] if rows else {"total":0,"pending":0,"wins":0,"losses":0,"voids":0,"overdue_pending":0,"needs_investigation":0}

    def predictions_for_date(self, fixture_date: str, *, source: str | None = None) -> list[dict[str, Any]]:
        sql="SELECT * FROM predictions WHERE fixture_date=:d"; p={"d":fixture_date}
        if source: sql += " AND source=:s"; p["s"]=source
        return self._rows(sql+" ORDER BY id DESC",p)

    def pending_predictions_for_date(self, fixture_date: str) -> list[dict[str, Any]]:
        return self._rows("SELECT * FROM predictions WHERE fixture_date=:d AND source='SCANNER' AND result='PENDING'",{"d":fixture_date})

    def settle_prediction_by_fixture(self, fixture_id: int, market_key: str, result: str, *, fixture_status: str, home_score: int|None, away_score: int|None) -> None:
        now=datetime.now(timezone.utc).isoformat(); result=result.upper()
        rows=self._rows("SELECT id,odds FROM predictions WHERE fixture_id=:f AND market_key=:m AND result='PENDING' AND COALESCE(settlement_eligible,1)=1",{"f":fixture_id,"m":market_key})
        with self.engine.begin() as conn:
            for row in rows:
                odds=float(row.get("odds") or 1.0); profit=(odds-1) if result=="WIN" else (-1 if result=="LOSS" else 0)
                conn.execute(text("UPDATE predictions SET result=:r,profit=:p,fixture_status=:s,home_score=:h,away_score=:a,settled_at=:t WHERE id=:id"),{"r":result,"p":profit,"s":fixture_status,"h":home_score,"a":away_score,"t":now,"id":row["id"]})
        if rows:
            self.refresh_performance_intelligence()

    def settle_prediction(self, prediction_id: int, result: str) -> None:
        rows=self._rows("SELECT odds FROM predictions WHERE id=:id",{"id":prediction_id})
        if not rows:return
        odds=float(rows[0].get("odds") or 1); result=result.upper(); profit=(odds-1) if result=="WIN" else (-1 if result=="LOSS" else 0)
        with self.engine.begin() as conn: conn.execute(text("UPDATE predictions SET result=:r,profit=:p,settled_at=:t,settlement_state='SETTLED' WHERE id=:id"),{"r":result,"p":profit,"t":datetime.now(timezone.utc).isoformat(),"id":prediction_id})
        self.refresh_performance_intelligence()

    def historical_accuracy(self, league: str|None=None) -> float:
        sql="SELECT result FROM predictions WHERE result IN ('WIN','LOSS')"; p={}
        if league: sql+=" AND league=:l";p["l"]=league
        rows=self._rows(sql,p); return sum(r["result"]=="WIN" for r in rows)/len(rows) if rows else .55

    def save_odds_snapshot(self, fixture_id: int, rows: list[dict[str, Any]], snapshot_type: str="LIVE") -> None:
        now=datetime.now(timezone.utc).isoformat()
        with self.engine.begin() as conn:
            for row in rows:
                if row.get("odds"):
                    conn.execute(text("INSERT INTO odds_snapshots(fixture_id,captured_at,market_key,odds,bookmaker,snapshot_type) VALUES (:f,:t,:m,:o,:b,:s)"),{"f":fixture_id,"t":now,"m":row["key"],"o":row["odds"],"b":row.get("bookmaker"),"s":snapshot_type})
                    conn.execute(text("UPDATE predictions SET closing_odds=:o, clv=CASE WHEN opening_odds IS NOT NULL THEN opening_odds/:o-1 ELSE NULL END WHERE fixture_id=:f AND market_key=:m AND result='PENDING'"),{"o":row["odds"],"f":fixture_id,"m":row["key"]})


