    def market_performance_snapshot(self) -> dict[str, dict[str, Any]]:
        """Return settlement-backed market performance for ranking.

        Prefer 30D when it has a meaningful sample; otherwise fall back to ALL.
        This is read-only and never recalculates performance inside the request.
        """
        rows = self._rows("""SELECT * FROM performance_rollups
            WHERE dimension_type='MARKET' AND period_key IN ('30D','ALL')""")
        grouped: dict[str, dict[str, dict[str, Any]]] = {}
        for row in rows:
            key = str(row.get("dimension_value") or "")
            grouped.setdefault(key, {})[str(row.get("period_key") or "ALL")] = row
        out: dict[str, dict[str, Any]] = {}
        for key, periods in grouped.items():
            recent = periods.get("30D") or {}
            all_time = periods.get("ALL") or {}
            if int(recent.get("sample") or 0) >= 10:
                chosen = dict(recent)
                chosen["performance_period"] = "30D"
            else:
                chosen = dict(all_time or recent)
                chosen["performance_period"] = "ALL" if all_time else "30D"
            out[key] = chosen
        return out

    def market_calibration_snapshot(self, market_probabilities: dict[str, float]) -> dict[str, dict[str, Any]]:
        """Settlement-backed empirical calibration near each current probability.

        Only WIN/LOSS rows participate. We use a ±10 percentage-point local
        window and cap the lookback to keep request cost predictable.
        """
        if not market_probabilities:
            return {}
        rows = self._rows("""SELECT market_key, probability, result
            FROM predictions
            WHERE result IN ('WIN','LOSS') AND market_key IS NOT NULL AND probability IS NOT NULL
            ORDER BY id DESC LIMIT 12000""")
        out: dict[str, dict[str, Any]] = {}
        for key, target in market_probabilities.items():
            try:
                target_p = float(target)
            except (TypeError, ValueError):
                continue
            samples = [r for r in rows if str(r.get("market_key") or "") == str(key)
                       and abs(float(r.get("probability") or 0) - target_p) <= 0.10]
            wins = sum(1 for r in samples if str(r.get("result") or "").upper() == "WIN")
            out[str(key)] = {
                "sample": len(samples), "wins": wins, "losses": len(samples)-wins,
                "target_probability": target_p,
            }
        return out

