    def settle_prediction_id(self, prediction_id: int, result: str, *, fixture_status: str,
                             home_score: int | None, away_score: int | None) -> bool:
        """Settle one prediction atomically using SQLAlchemy Core.

        Reading and updating happen in the same transaction. The PENDING predicate
        prevents duplicate settlement when manual and scheduled jobs overlap.
        """
        result = result.upper()
        if result not in {"WIN", "LOSS", "VOID"}:
            raise ValueError(f"Unsupported settlement result: {result}")

        with self.engine.begin() as conn:
            row = conn.execute(
                select(self._predictions.c.odds, self._predictions.c.result)
                .where(self._predictions.c.id == int(prediction_id))
                .with_for_update()
            ).mappings().first()
            if not row or row.get("result") != "PENDING":
                return False

            odds = float(row.get("odds") or 1.0)
            profit = (odds - 1.0) if result == "WIN" else (-1.0 if result == "LOSS" else 0.0)
            statement = (
                update(self._predictions)
                .where(
                    self._predictions.c.id == int(prediction_id),
                    self._predictions.c.result == "PENDING",
                )
                .values(
                    result=result,
                    profit=profit,
                    fixture_status=str(fixture_status),
                    home_score=home_score,
                    away_score=away_score,
                    settled_at=datetime.now(timezone.utc).isoformat(),
                    settlement_checked_at=datetime.now(timezone.utc).isoformat(),
                    settlement_state="SETTLED",
                    settlement_reason="Settlement selesai",
                    last_api_status=str(fixture_status),
                    next_retry_at=None,
                )
            )
            update_result = conn.execute(statement)
            return bool(update_result.rowcount)

