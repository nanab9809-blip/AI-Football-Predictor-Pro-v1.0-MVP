    def pending_scanner_predictions(self, limit: int = 1000, *, overdue_only: bool = False) -> list[dict[str, Any]]:
        """Return one unified queue of pending predictions.

        Candidate selection deliberately depends only on the prediction still being
        PENDING, having a fixture ID, and not having been explicitly isolated for
        manual investigation.  ``source``, ``next_retry_at`` and retry metadata are
        diagnostics only; they must never hide old predictions from settlement.

        Overdue mode narrows this same queue to fixture dates before today's WITA
        date.  Within either mode the oldest fixture date is processed first, while
        ``settlement_checked_at`` rotates repeatedly non-final fixtures behind rows
        that have not yet been checked.
        """
        today_wita = datetime.now(ZoneInfo("Asia/Makassar")).date().isoformat()
        overdue_clause = "AND SUBSTR(fixture_date, 1, 10) < :today" if overdue_only else ""
        return self._rows(
            f"""SELECT * FROM predictions
               WHERE result='PENDING'
                 AND COALESCE(settlement_eligible,1)=1
                 AND fixture_id IS NOT NULL
                 AND COALESCE(settlement_state, 'PENDING') <> 'NEEDS_INVESTIGATION'
                 {overdue_clause}
               ORDER BY
                 CASE WHEN SUBSTR(fixture_date, 1, 10) < :today THEN 0 ELSE 1 END,
                 SUBSTR(fixture_date, 1, 10) ASC,
                 CASE WHEN settlement_checked_at IS NULL THEN 0 ELSE 1 END,
                 settlement_checked_at ASC,
                 id ASC
               LIMIT :n""",
            {"n": limit, "today": today_wita},
        )

