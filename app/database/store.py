    def license_history_detailed(self, user_id: int, limit: int = 100) -> list[dict[str, Any]]:
        rows = self._rows("""SELECT h.*, actor.username AS changed_by_username
            FROM license_history h LEFT JOIN user_accounts actor ON actor.id=h.changed_by
            WHERE h.user_id=:id ORDER BY h.id DESC LIMIT :limit""", {"id": user_id, "limit": limit})
        def mask_key(value: Any) -> str | None:
            text_value = str(value or "").strip()
            if not text_value:
                return None
            if len(text_value) <= 8:
                return "****"
            return f"{text_value[:5]}-****-****-{text_value[-4:]}"

        for row in rows:
            if row.get("changed_at") not in (None, ""):
                row["changed_at"] = self._as_utc(row.get("changed_at"))
            row["old_key_masked"] = mask_key(row.get("old_key"))
            row["new_key_masked"] = mask_key(row.get("new_key"))
        return rows
